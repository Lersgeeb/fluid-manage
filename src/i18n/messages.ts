export const messages = { es, en } satisfies Record<string, Record<MessageKey, string>>;

export type Language = keyof typeof messages;
export const LANGUAGES: readonly Language[] = ['es', 'en'];

export type Translate = (key: MessageKey, params?: Record<string, string | number>) => string;

export function createTranslator(language: Language): Translate {
  const dictionary: Record<MessageKey, string> = messages[language];
  return (key, params) =>
    params
      ? dictionary[key].replace(/\{(\w+)\}/g, (match, name: string) => String(params[name] ?? match))
      : dictionary[key];
}
